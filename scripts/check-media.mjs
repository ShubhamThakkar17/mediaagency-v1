#!/usr/bin/env node
/**
 * Verify every asset in content/media.ts (BRIEF §8.4).
 *
 *   node scripts/check-media.mjs            # write MEDIA_REPORT.md, always exit 0
 *   node scripts/check-media.mjs --strict   # exit 1 if any URL failed
 *
 * Sends a HEAD request for each non-empty `src` (Unsplash URLs get the same
 * sizing params the site uses). If Node's fetch cannot reach the network
 * (e.g. it ignores a sandbox HTTPS proxy), it falls back to `curl -sI`.
 * A URL is marked `unchecked` only when both fail at the network level.
 */
import { execFile } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { tsImport } from 'tsx/esm/api';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPORT = resolve(ROOT, 'MEDIA_REPORT.md');
const TIMEOUT_MS = 15_000;
const CONCURRENCY = 6;
const STRICT = process.argv.includes('--strict');

const { MEDIA } = await tsImport(pathToFileURL(resolve(ROOT, 'content/media.ts')).href, import.meta.url);

/** The URL the site actually requests: Unsplash gets sizing params. */
function probeUrl(src) {
  const u = new URL(src);
  if (u.hostname === 'images.unsplash.com' && !u.search) {
    u.search = 'w=800&q=70&auto=format&fit=crop';
  }
  return u.toString();
}

async function headWithFetch(url) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), TIMEOUT_MS);
  try {
    let res = await fetch(url, { method: 'HEAD', redirect: 'follow', signal: ctrl.signal });
    // Some CDNs reject HEAD; retry with a ranged GET before calling it failed.
    if (res.status === 405 || res.status === 403) {
      res = await fetch(url, { method: 'GET', headers: { Range: 'bytes=0-0' }, redirect: 'follow', signal: ctrl.signal });
      res.body?.cancel().catch(() => {});
    }
    return { status: res.status, type: res.headers.get('content-type') ?? '' };
  } finally {
    clearTimeout(timer);
  }
}

function headWithCurl(url) {
  return new Promise((resolvePromise, reject) => {
    execFile(
      'curl',
      ['-sIL', '-o', '/dev/null', '-m', String(TIMEOUT_MS / 1000), '-w', '%{http_code} %{content_type}', url],
      { timeout: TIMEOUT_MS + 5_000 },
      (err, stdout) => {
        const [code, ...rest] = String(stdout ?? '').trim().split(' ');
        const status = Number(code);
        if (!status) return reject(err ?? new Error('curl: no HTTP status'));
        resolvePromise({ status, type: rest.join(' ') });
      },
    );
  });
}

async function check(asset) {
  if (!asset.src) return { status: 'empty' };
  const url = probeUrl(asset.src);
  let result;
  try {
    result = await headWithFetch(url);
  } catch {
    try {
      result = await headWithCurl(url);
    } catch {
      return { status: 'unchecked' };
    }
  }
  const okType = asset.kind === 'video' ? /^(video|application\/octet-stream)/ : /^image\//;
  if (result.status >= 200 && result.status < 300 && okType.test(result.type)) return { status: 'ok' };
  if (result.status >= 200 && result.status < 300) return { status: 'failed', code: `${result.status}, ${result.type || 'no type'}` };
  return { status: 'failed', code: String(result.status) };
}

async function pool(items, size, fn) {
  const out = new Array(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(size, items.length) }, async () => {
      while (next < items.length) {
        const i = next++;
        out[i] = await fn(items[i]);
      }
    }),
  );
  return out;
}

const results = await pool(MEDIA, CONCURRENCY, check);

const counts = { ok: 0, failed: 0, unchecked: 0, empty: 0 };
for (const r of results) counts[r.status]++;

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const statusText = (r) =>
  r.status === 'failed' ? `failed (${r.code})` : r.status === 'empty' ? 'fallback (no asset)' : r.status;
const link = (url, label) => (url ? `[${cell(label)}](${url})` : '');

const date = new Date().toISOString().slice(0, 10);
const lines = [
  '# Media report',
  '',
  `Generated by \`node scripts/check-media.mjs\` on ${date}.`,
  '',
  `**${counts.ok} ok · ${counts.failed} failed · ${counts.unchecked} unchecked · ${counts.empty} empty** (of ${MEDIA.length} slots)`,
  '',
  'Empty slots render the branded fallback in `<SmartMedia>`; IMAGE_PROMPTS.md has a prompt for each.',
  '',
  '| id | kind | licence | status | credit | source page |',
  '| --- | --- | --- | --- | --- | --- |',
  ...MEDIA.map((m, i) => {
    const r = results[i];
    const empty = r.status === 'empty';
    return `| \`${m.id}\` | ${m.kind} | ${empty ? '–' : cell(m.licence)} | ${statusText(r)} | ${
      empty ? '–' : link(m.creditUrl, m.credit) || cell(m.credit)
    } | ${empty ? '–' : link(m.sourcePage, 'page')} |`;
  }),
  '',
];

await writeFile(REPORT, lines.join('\n'));
console.log(
  `check-media: ${counts.ok} ok, ${counts.failed} failed, ${counts.unchecked} unchecked, ${counts.empty} empty -> MEDIA_REPORT.md`,
);
for (const [i, r] of results.entries()) {
  if (r.status === 'failed') console.log(`  failed: ${MEDIA[i].id} (${r.code}) ${MEDIA[i].src}`);
}
process.exit(STRICT && counts.failed > 0 ? 1 : 0);
